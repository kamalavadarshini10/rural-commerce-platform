"""
baseline.py - "Baseline" mode evaluation.

Baseline simulates a delivery system with:
  - Basic address/location information only
  - NO access-instruction capture, reuse, or reliability scoring
  - NO customer confirmation loop
  - NO repeat-failure awareness

It reads the same synthetic database as the prototype (generated by
generate_dataset.py) but only looks at raw delivery/outcome data,
completely ignoring the AccessInstructions / InstructionVersions /
CustomerConfirmations tables. This gives an honest "what if we had
no instruction-reuse system at all" comparison point.

Run: python baseline.py
"""
import sqlite3
import os

DB_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'backend', 'database', 'ruralroute.db')


def run_baseline():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    cur.execute("SELECT COUNT(*) FROM DeliveryOutcomes")
    total_attempts = cur.fetchone()[0]

    cur.execute("SELECT COUNT(*) FROM DeliveryOutcomes WHERE outcome = 'SUCCESS'")
    total_success = cur.fetchone()[0]

    cur.execute("SELECT COUNT(*) FROM DeliveryOutcomes WHERE outcome = 'FAILURE'")
    total_failure = cur.fetchone()[0]

    # First-attempt success rate: did attempt_number == 1 succeed?
    cur.execute("SELECT COUNT(*) FROM DeliveryOutcomes WHERE attempt_number = 1")
    first_attempts = cur.fetchone()[0]
    cur.execute("SELECT COUNT(*) FROM DeliveryOutcomes WHERE attempt_number = 1 AND outcome = 'SUCCESS'")
    first_attempt_success = cur.fetchone()[0]

    # Repeat-failure rate: locations with >1 recorded failure, over all locations that have ANY failure
    cur.execute("""
        SELECT COUNT(*) FROM (
            SELECT location_id FROM DeliveryOutcomes WHERE outcome = 'FAILURE'
            GROUP BY location_id HAVING COUNT(*) > 1
        )
    """)
    repeat_failure_locations = cur.fetchone()[0]

    cur.execute("""
        SELECT COUNT(DISTINCT location_id) FROM DeliveryOutcomes WHERE outcome = 'FAILURE'
    """)
    locations_with_failure = cur.fetchone()[0]

    conn.close()

    metrics = {
        "mode": "BASELINE (no instruction reuse, no reliability engine)",
        "total_attempts": total_attempts,
        "success_count": total_success,
        "failure_count": total_failure,
        "success_rate": round(total_success / total_attempts, 3) if total_attempts else 0,
        "failure_rate": round(total_failure / total_attempts, 3) if total_attempts else 0,
        "first_attempt_success_rate": round(first_attempt_success / first_attempts, 3) if first_attempts else 0,
        "repeat_failure_locations": repeat_failure_locations,
        "repeat_failure_rate": round(repeat_failure_locations / locations_with_failure, 3) if locations_with_failure else 0,
        # Baseline has none of these capabilities by definition
        "instruction_reuse_rate": 0,
        "customer_confirmation_rate": 0,
        "agent_input_effort": "HIGH (no pre-filled instructions; agent must free-type notes every attempt)"
    }
    return metrics


if __name__ == '__main__':
    m = run_baseline()
    print("=== BASELINE Evaluation (Synthetic prototype evaluation) ===")
    for k, v in m.items():
        print(f"{k}: {v}")
